test('PostgreSQL survives an API container restart', async ({ request }) => {
  const registration = await request.post('/app-api/register', { data: { name: 'Persistence test', organization: 'Persistence', email: 'persist-' + Date.now() + '@example.test', password } });
  expect(registration.status()).toBe(201);
  const { token } = await registration.json();
  const headers = { Authorization: 'Bearer ' + token };
  const project = await request.post('/app-api/projects', { headers, data: { name: 'Persisted project' } });
  expect(project.status()).toBe(201);
  const { id } = await project.json();
  const { execFileSync } = await import('node:child_process');
  execFileSync('docker', ['compose', '-f', '../compose.yaml', 'restart', 'db', 'api']);
  await expect.poll(async () => { try { return (await request.get('/health')).status(); } catch { return 0; } }, { timeout: 30000 }).toBe(200);
  const projects = await request.get('/app-api/projects', { headers });
  expect(projects.status()).toBe(200);
  expect((await projects.json()).some((item: { id: string }) => item.id === id)).toBe(true);
});
